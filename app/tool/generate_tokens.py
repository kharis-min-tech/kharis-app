#!/usr/bin/env python3
"""Generate lib/theme/kharis_tokens.g.dart from tokens/kharis_tokens.json.

The JSON file is the single source of truth for the Kharis design tokens.
Change a value there, then run from the project root:

    python3 tool/generate_tokens.py

No dependencies beyond Python 3.8+.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tokens" / "kharis_tokens.json"
OUT = ROOT / "lib" / "theme" / "kharis_tokens.g.dart"

REF = re.compile(r"^\{([^}]+)\}$")


def load():
    return json.loads(SRC.read_text(encoding="utf-8"))


def lookup(tokens, path):
    node = tokens
    for part in path.split("."):
        node = node[part]
    return node["$value"]


def resolve(tokens, value, seen=()):
    if isinstance(value, str):
        m = REF.match(value)
        if m:
            ref = m.group(1)
            if ref in seen:
                raise ValueError(f"Circular token reference: {ref}")
            return resolve(tokens, lookup(tokens, ref), seen + (ref,))
    return value


def dart_color(hex_value):
    h = hex_value.lstrip("#").lower()
    if len(h) == 6:
        rgb, alpha = h, "ff"
    elif len(h) == 8:
        rgb, alpha = h[:6], h[6:]
    else:
        raise ValueError(f"Bad colour: {hex_value}")
    return f"Color(0x{alpha.upper()}{rgb.upper()})"


def px(value):
    if isinstance(value, (int, float)):
        return value
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)px", value.strip())
    if not m:
        raise ValueError(f"Expected a px dimension, got {value!r}")
    n = float(m.group(1))
    return int(n) if n.is_integer() else n


def num(n):
    if isinstance(n, float) and n.is_integer():
        n = int(n)
    return str(n)


def dbl(n):
    s = num(n)
    return s if "." in s else s + ".0"


def doc(desc, indent="  "):
    return f"{indent}/// {desc}\n" if desc else ""


def entries(group):
    return [(k, v) for k, v in group.items() if not k.startswith("$")]


def shadow_list(tokens, token):
    layers = token["$value"]
    if not layers:
        return "<BoxShadow>[]"
    parts = []
    for layer in layers:
        color = dart_color(resolve(tokens, layer["color"]))
        x, y = px(layer["offsetX"]), px(layer["offsetY"])
        blur, spread = px(layer["blur"]), px(layer["spread"])
        extra = f", spreadRadius: {dbl(spread)}" if spread else ""
        parts.append(f"BoxShadow(color: {color}, offset: Offset({dbl(x)}, {dbl(y)}), blurRadius: {dbl(blur)}{extra})")
    return "<BoxShadow>[" + ", ".join(parts) + "]"


def generate(tokens):
    out = []
    w = out.append
    w("// GENERATED by tool/generate_tokens.py from tokens/kharis_tokens.json.\n")
    w("// Do not edit by hand: change the JSON and run `python3 tool/generate_tokens.py`.\n\n")
    w("import 'package:flutter/material.dart';\n\n")

    # Brand palette
    w("/// Kharis brand palette. Screens never use these directly: use the\n")
    w("/// [KharisColors] roles through `context.k` so light and dark mode stay correct.\n")
    w("abstract final class KBrand {\n")
    for name, t in entries(tokens["brand"]):
        w(doc(t.get("$description")))
        w(f"  static const Color {name} = {dart_color(resolve(tokens, t['$value']))};\n")
    w("}\n\n")

    # Palettes
    light, dark = tokens["color"]["light"], tokens["color"]["dark"]
    names = [k for k, _ in entries(light)]
    if names != [k for k, _ in entries(dark)]:
        raise ValueError("color.light and color.dark must define the same roles in the same order")
    w("/// Colour roles, registered on ThemeData as a ThemeExtension. Read them with\n")
    w("/// `context.k` (see kharis_theme.dart).\n")
    w("///\n/// Brand rule: light mode = yellow primary + purple highlight;\n")
    w("/// dark mode = purple primary + yellow highlight. Widgets use roles only,\n")
    w("/// so they are correct in both modes without checking brightness.\n")
    w("@immutable\n")
    w("final class KharisColors extends ThemeExtension<KharisColors> {\n")
    w("  const KharisColors({\n")
    for n in names:
        w(f"    required this.{n},\n")
    w("  });\n\n")
    for n in names:
        w(doc(light[n].get("$description")))
        w(f"  final Color {n};\n")
    for mode_name, mode in (("light", light), ("dark", dark)):
        w(f"\n  static const KharisColors {mode_name} = KharisColors(\n")
        for n in names:
            w(f"    {n}: {dart_color(resolve(tokens, mode[n]['$value']))},\n")
        w("  );\n")
    w("\n  @override\n  KharisColors copyWith({\n")
    for n in names:
        w(f"    Color? {n},\n")
    w("  }) {\n    return KharisColors(\n")
    for n in names:
        w(f"      {n}: {n} ?? this.{n},\n")
    w("    );\n  }\n")
    w("\n  @override\n  KharisColors lerp(covariant ThemeExtension<KharisColors>? other, double t) {\n")
    w("    if (other is! KharisColors) return this;\n    return KharisColors(\n")
    for n in names:
        w(f"      {n}: Color.lerp({n}, other.{n}, t)!,\n")
    w("    );\n  }\n")
    w("}\n\n")

    # Typography
    family = resolve(tokens, tokens["font"]["family"]["$value"]).replace(" ", "")
    w("/// One step of the type scale. Turn it into a TextStyle with\n")
    w("/// `KharisText.style()` (see kharis_text.dart).\n")
    w("final class KTypeToken {\n")
    w("  const KTypeToken({required this.size, required this.height, required this.weight, required this.trackingEm, this.uppercase = false});\n")
    w("  final double size;\n  final double height;\n  final int weight;\n")
    w("  /// Letter spacing in em. Multiply by [size] for Flutter's logical pixels.\n")
    w("  final double trackingEm;\n  final bool uppercase;\n")
    w("  double get letterSpacing => size * trackingEm;\n")
    w("}\n\n")
    w("abstract final class KType {\n")
    w(f"  /// Asset font family declared in pubspec.yaml.\n  static const String fontFamily = '{family}';\n")
    for name, t in entries(tokens["typography"]):
        v = t["$value"]
        em = float(str(v["letterSpacing"]).replace("em", ""))
        upper = ", uppercase: true" if v.get("textCase") == "uppercase" else ""
        w(doc(t.get("$description")))
        w(f"  static const KTypeToken {name} = KTypeToken(size: {dbl(px(v['fontSize']))}, height: {dbl(v['lineHeight'])}, weight: {v['fontWeight']}, trackingEm: {dbl(em)}{upper});\n")
    w("}\n\n")

    # Dimensions
    for group, cls, title in (("space", "KSpace", "Spacing scale. Gaps, padding and margins use these values only."),
                              ("radius", "KRadius", "Corner radii (base 12, pill shapes off)."),
                              ("size", "KSize", "Component sizes and layout constants, in logical pixels."),
                              ("ratio", "KRatio", "Unitless numbers: opacities, gradient stops, width shares and scale factors.")):
        w(f"/// {title}\nabstract final class {cls} {{\n")
        for name, t in entries(tokens[group]):
            w(doc(t.get("$description")))
            w(f"  static const double {name} = {dbl(px(t['$value']))};\n")
        w("}\n\n")

    # Shadows
    w("/// Elevation shadows. The design is flat: cards use a 1px border plus,\n/// in light mode only, a soft shadow.\n")
    w("abstract final class KShadow {\n")
    for name, t in entries(tokens["shadow"]):
        if "$value" in t:
            w(f"  static const List<BoxShadow> {name} = {shadow_list(tokens, t)};\n")
        else:
            for mode_name, mt in entries(t):
                w(f"  static const List<BoxShadow> {name}{mode_name[0].upper()}{mode_name[1:]} = {shadow_list(tokens, mt)};\n")
    w("}\n\n")

    # Motion
    w("abstract final class KMotion {\n")
    for name, t in entries(tokens["motion"]):
        ms = int(str(t["$value"]).replace("ms", ""))
        w(doc(t.get("$description")))
        w(f"  static const Duration {name} = Duration(milliseconds: {ms});\n")
    w("}\n")
    return "".join(out)


def main():
    dart = generate(load())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(dart, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
